// Unicode has raised and lowered forms of the digits, a few symbols and most
// letters, which is how a terminal can show x² or H₂O at all. The sets are
// incomplete - there is no superscript q, and only some capitals - so
// conversion is all or nothing: a mix of small and full-size letters reads
